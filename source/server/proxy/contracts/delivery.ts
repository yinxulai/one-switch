/**
 * 交付方式：把字节交回客户端的方式。
 *
 * 它与「上游用什么插座」({@link TransportKind}) 是**两根正交的轴**，必须分开命名：
 * 上游可以是 HTTP 或 WebSocket，客户端交付可以是攒完再发或边收边发，四种组合都成立。
 * 一次 WebSocket 上游 + 逐帧交付的交换，用「是不是 HTTP 流式」来描述只能是自相矛盾的。
 *
 * 为什么不把 SSE 做成一档传输（`http-stream` / `http-sse`）：那样会同时错两件事。
 * 一是它与 `http` 在建连、TLS、超时、abort、出网方式上一字不差，差别只在响应体怎么分帧——
 * 那是**封装**的属性，不是传输的属性，混进来会稀释「新增传输只需实现 `Transport`」的价值。
 * 二是客户端「要不要增量」会因此漏进路由决策（规划器据此筛候选），而客户端偏好
 * 从来不改变哪个上游端点合法。
 *
 * SSE 是**分帧格式**，它的判定留在帧层（读 `content-type: text/event-stream`），不在这里：
 * 这里只表达客户端的意图，上游是否真的逐块回由响应头决定。
 */
export type DeliveryMode = 'buffered' | 'stream'
