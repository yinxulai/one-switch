        "relative flex h-8 w-full cursor-default items-center gap-1.5 rounded-lg px-2 pr-8 text-[13px] leading-4 text-text-secondary outline-hidden select-none focus:bg-state-base-hover focus:text-text-primary focus:**:text-text-primary data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
